def preprocessing_fingerprint() -> str:
    """A content fingerprint stored inside the files, separate from DATASET_ID.

    ``DATASET_ID`` stays fixed because the requested filenames are an external
    contract.  This fingerprint makes configuration drift detectable without
    pretending that the supplied identifier was generated by this version of
    the code.
    """
    payload = {
        "city": CITY,
        "dataset_id": DATASET_ID,
        "raster": PLANET_RASTER_NAME,
        "prep": {
            **PREP,
            "positive_damage_codes": list(PREP["positive_damage_codes"]),
            "channels": list(PREP["channels"]),
        },
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(encoded).hexdigest()


# ---------------------------------------------------------------------------
# Labels: May target plus a July-only false-negative guard
# ---------------------------------------------------------------------------

def _read_label_table(date: str) -> pd.DataFrame:
    path = label_path(date)
    if not path.exists():
        raise FileNotFoundError(f"Missing label file: {path}")

    raw = pd.read_csv(path, low_memory=False)
    required = {"system:index", "class", ".geo"}
    missing = required - set(raw.columns)
    if missing:
        raise ValueError(f"{path.name} is missing required columns: {sorted(missing)}")
    if raw["system:index"].isna().any() or raw["system:index"].duplicated().any():
        raise ValueError(f"{path.name} must contain unique, non-null system:index values")
    classes = set(raw["class"].dropna().astype(int).unique())
    if not classes <= {0, 1}:
        raise ValueError(f"{path.name} has non-binary class values: {sorted(classes)}")

    return raw


def build_filtered_buildings() -> tuple[gpd.GeoDataFrame, dict[str, int | float]]:
    """Build the canonical May table and remove labels contaminated by July.

    The May assessment supplies the target.  A building that is intact in May
    but damaged in July is excluded because the June Planet post composite may
    already show the later event.  May positives remain positives; May intact
    buildings are retained only when July also calls them intact.
    """
    # Keep July as a plain DataFrame. Parsing 218k duplicate polygons twice is
    # expensive in Colab and unnecessary because May is the geometry source.
    may_raw = _read_label_table(MAY_DATE)
    july_raw = _read_label_table(JULY_DATE)

    may_ids = set(may_raw["system:index"])
    july_ids = set(july_raw["system:index"])
    if may_ids != july_ids:
        raise ValueError(
            "May and July footprint IDs differ: "
            f"{len(may_ids - july_ids)} May-only and {len(july_ids - may_ids)} July-only"
        )

    may_raw_by_id = may_raw.set_index("system:index")
    july_raw_by_id = july_raw.set_index("system:index").loc[may_raw_by_id.index]
    geometry_mismatches = int((may_raw_by_id[".geo"] != july_raw_by_id[".geo"]).sum())
    if geometry_mismatches:
        raise ValueError(
            f"May and July contain {geometry_mismatches:,} footprint geometry mismatches"
        )

    may_by_id = may_raw_by_id
    july_by_id = july_raw_by_id
    y_may = may_by_id["class"].astype(np.int8)
    y_july = july_by_id["class"].astype(np.int8)

    # July is only a guard against contaminated May negatives. A May positive
    # remains a May positive even if the later release no longer contains that
    # assessment: cumulative UNOSAT releases can revise classifications or
    # omit earlier points, so treating 1 -> 0 as a true recovery would be wrong.
    may_positive_july_negative = (y_may == 1) & (y_july == 0)
    future_damage = (y_may == 0) & (y_july == 1)
    keep = ~future_damage

    kept_may = may_by_id.loc[keep]
    base_columns = [c for c in ("area",) if c in kept_may.columns]
    geometries = gpd.GeoSeries(
        [shape(json.loads(value)) for value in kept_may[".geo"]],
        index=kept_may.index,
        crs="EPSG:4326",
    )
    out = gpd.GeoDataFrame(
        kept_may[base_columns].copy(), geometry=geometries, crs="EPSG:4326"
    )
    out[f"class_{MAY_DATE}"] = y_may
    out[f"class_{JULY_DATE}"] = y_july
    out["class"] = y_may

    # Keep provenance and label-quality fields with explicit dates so later
    # modeling cannot accidentally confuse July information with a May input.
    for date, frame in ((MAY_DATE, may_by_id), (JULY_DATE, july_by_id)):
        for column in ("damage_pts", "severity", "confidence", "max_change"):
            if column in frame.columns:
                out[f"{column}_{date}"] = frame[column]

    out = out.reset_index()
    out = gpd.GeoDataFrame(out, geometry="geometry", crs="EPSG:4326")
    out = out.sort_values("system:index").reset_index(drop=True)

    geometry_ok = out.geometry.notna() & ~out.geometry.is_empty & out.geometry.is_valid
    invalid_geometry = int((~geometry_ok).sum())
    if invalid_geometry:
        out = out.loc[geometry_ok].reset_index(drop=True)

    summary: dict[str, int | float] = {
        "may_rows": int(len(may_by_id)),
        "future_damage_removed": int(future_damage.sum()),
        "may_positive_july_negative_kept": int(may_positive_july_negative.sum()),
        "invalid_geometry_removed": invalid_geometry,
        "filtered_rows": int(len(out)),
        "damaged": int(out["class"].sum()),
        "intact": int((out["class"] == 0).sum()),
        "damaged_fraction": float(out["class"].mean()),
    }
    return out, summary


def footprint_latitude_reference(date: str = MAY_DATE) -> pd.DataFrame:
    """Full notebook-0 footprint IDs and centroid latitudes for spatial bands.

    S1 fits latitude quantiles before applying imagery usability. Planet must
    therefore use this unfiltered reference rather than refitting cutoffs after
    future-damage and raster-coverage exclusions.
    """
    raw = _read_label_table(date)
    latitudes = np.fromiter(
        (shape(json.loads(value)).centroid.y for value in raw[".geo"]),
        dtype=np.float64,
        count=len(raw),
    )
    if not np.isfinite(latitudes).all():
        raise ValueError(f"{date} footprint centroids contain non-finite latitudes")
    return pd.DataFrame(
        {
            "system:index": raw["system:index"].astype(str).to_numpy(),
            "lat": latitudes,
        }
    )


