def set_random_seed(seed: int, deterministic: bool = True) -> None:
    """Seed Python, NumPy and PyTorch for a reproducible experiment."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    if deterministic:
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False


def latitude_quantile_spatial_split(
    table: pd.DataFrame,
    bands: dict[str, tuple[float, float]] | None = None,
    reference: pd.DataFrame | None = None,
) -> dict[str, object]:
    """Apply notebook 2's exact S1 latitude-quantile split to Planet rows.

    The defaults are train 0.55--1.00, stack 0.42--0.55, validation
    0.33--0.42, and test 0.00--0.33. There are no buffer gaps. ``reference``
    should be the full notebook-0 table from :func:`footprint_latitude_reference`.
    Bands are then joined to filtered Planet rows by footprint ID, matching S1's
    fit-bands-first, apply-imagery-usability-second order.
    """
    if bands is None:
        bands = {
            "train": (0.55, 1.00),
            "stack": (0.42, 0.55),
            "val": (0.33, 0.42),
            "test": (0.00, 0.33),
        }
    expected = ("train", "stack", "val", "test")
    if tuple(bands) != expected:
        raise ValueError(f"bands must be ordered exactly as {expected}")
    reference = table[["system:index", "lat"]].copy() if reference is None else reference.copy()
    required = {"system:index", "lat"}
    missing = required - set(reference.columns)
    if missing:
        raise ValueError(f"Latitude reference is missing columns: {sorted(missing)}")
    if reference["system:index"].isna().any() or reference["system:index"].duplicated().any():
        raise ValueError("Latitude reference IDs must be unique and non-null")
    reference["system:index"] = reference["system:index"].astype(str)
    latitude = reference["lat"].to_numpy(np.float64)
    if not np.isfinite(latitude).all():
        raise ValueError("Latitude contains non-finite values")

    masks: dict[str, np.ndarray] = {}
    thresholds: dict[str, tuple[float, float]] = {}
    for name, interval in bands.items():
        lo, hi = (float(value) for value in interval)
        if not 0 <= lo < hi <= 1:
            raise ValueError(f"Invalid quantile band for {name}: {interval}")
        qlo, qhi = np.quantile(latitude, [lo, hi])
        masks[name] = (latitude >= qlo) & (latitude <= qhi)
        thresholds[name] = (float(qlo), float(qhi))

    membership = np.stack([masks[name] for name in expected], axis=1).sum(axis=1)
    if (membership > 1).any():
        counts = {name: int(masks[name][membership > 1].sum()) for name in expected}
        raise ValueError(
            "Tied latitudes overlap S1 quantile boundaries; choose an explicit "
            f"tie rule before training. Overlap counts: {counts}"
        )
    if (membership == 0).any():
        raise ValueError("The S1 quantile bands do not assign every Planet row")

    reference_assignment = np.full(len(reference), "unused", dtype="U6")
    for name in expected:
        reference_assignment[masks[name]] = name
    role_by_id = pd.Series(
        reference_assignment, index=reference["system:index"], name="split_role"
    )
    table_ids = table["system:index"].astype(str)
    missing_ids = ~table_ids.isin(role_by_id.index)
    if missing_ids.any():
        raise ValueError(
            f"{int(missing_ids.sum()):,} Planet rows are absent from the split reference"
        )
    assignment = role_by_id.loc[table_ids].to_numpy(dtype="U6")
    indices: dict[str, np.ndarray] = {}
    for name in expected:
        indices[name] = np.flatnonzero(assignment == name)
        if not len(indices[name]):
            raise ValueError(f"Latitude split produced an empty {name} band")

    xy = table[["centroid_x", "centroid_y"]].to_numpy(np.float64)
    return {
        **indices,
        "assignment": assignment,
        "coordinate": latitude,
        "xy": xy,
        "bands": {name: tuple(map(float, bands[name])) for name in expected},
        "latitude_thresholds": thresholds,
        "reference_rows": int(len(reference)),
    }


def spatial_split_metadata(split: dict[str, object]) -> dict[str, object]:
    """JSON-serializable fitted split definition (indices stay out of JSON)."""
    return {
        "type": "s1_exact_latitude_quantile_bands",
        "bands": {name: list(values) for name, values in split["bands"].items()},
        "latitude_thresholds": {
            name: list(values) for name, values in split["latitude_thresholds"].items()
        },
        "buffer_m": 0.0,
        "reference_rows": split["reference_rows"],
        "counts": {
            name: int(len(split[name]))
            for name in ("train", "stack", "val", "test")
        },
    }


def planet_band_indices(bands: Sequence[str]) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """NPZ channel positions for matching pre/post Planet band names."""
    requested = tuple(str(band).upper() for band in bands)
    unknown = set(requested) - set(PLANET_BANDS)
    if unknown:
        raise ValueError(f"Unknown Planet bands: {sorted(unknown)}")
    if len(set(requested)) != len(requested):
        raise ValueError("Planet band list contains duplicates")
    pre = tuple(PLANET_CHANNELS.index(f"ps_pre_{band}") for band in requested)
    post = tuple(PLANET_CHANNELS.index(f"ps_post_{band}") for band in requested)
    return pre, post


def estimate_shared_percentiles(
    x: np.ndarray,
    train_indices: Sequence[int] | np.ndarray,
    bands: Sequence[str] = PLANET_BANDS,
    lower: float = 2.0,
    upper: float = 98.0,
    sample_patches: int = 20_000,
    seed: int = 0,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Estimate shared pre/post robust scaling from training rows only.

    One lower/upper pair is fitted per physical band using both acquisition
    periods. Sampling caps the percentile workspace while remaining fully
    reproducible. The returned third value contains the sampled row indices.
    """
    if not 0 <= lower < upper <= 100:
        raise ValueError("Percentiles must satisfy 0 <= lower < upper <= 100")
    indices = np.asarray(train_indices, dtype=np.int64)
    if not len(indices):
        raise ValueError("Cannot estimate normalization from an empty training split")
    if sample_patches and len(indices) > sample_patches:
        rng = np.random.default_rng(seed)
        sampled = np.sort(rng.choice(indices, size=sample_patches, replace=False))
    else:
        sampled = np.sort(indices)

    pre_indices, post_indices = planet_band_indices(bands)
    lo = np.empty(len(pre_indices), np.float32)
    hi = np.empty(len(pre_indices), np.float32)
    for j, (pre_i, post_i) in enumerate(zip(pre_indices, post_indices)):
        values = np.concatenate(
            [
                np.asarray(x[sampled, pre_i], dtype=np.float32).reshape(-1),
                np.asarray(x[sampled, post_i], dtype=np.float32).reshape(-1),
            ]
        )
        finite = values[np.isfinite(values)]
        if not len(finite):
            raise ValueError(f"Band {bands[j]} has no finite training pixels")
        lo[j], hi[j] = np.percentile(finite, [lower, upper]).astype(np.float32)
        if hi[j] <= lo[j]:
            raise ValueError(f"Band {bands[j]} has a degenerate normalization range")
        del values, finite
    return lo, hi, sampled


class PlanetPairDataset(Dataset):
    """Lazy normalized Planet pairs returned as one pre/post channel stack."""

    def __init__(
        self,
        x: np.ndarray,
        y: np.ndarray,
        indices: Sequence[int] | np.ndarray,
        bands: Sequence[str],
        lo: Sequence[float] | np.ndarray,
        hi: Sequence[float] | np.ndarray,
        augment: bool = False,
        brightness_jitter: float = 0.0,
    ) -> None:
        self.x = x
        self.y = np.asarray(y, dtype=np.float32)
        self.indices = np.asarray(indices, dtype=np.int64)
        self.pre_indices, self.post_indices = planet_band_indices(bands)
        self.lo = np.asarray(lo, dtype=np.float32)[:, None, None]
        self.scale = np.maximum(
            np.asarray(hi, dtype=np.float32)[:, None, None] - self.lo, 1e-6
        )
        self.augment = bool(augment)
        self.brightness_jitter = float(brightness_jitter)

    def __len__(self) -> int:
        return len(self.indices)

    def __getitem__(self, item: int) -> tuple[torch.Tensor, torch.Tensor]:
        position = int(self.indices[item])
        patch = np.asarray(self.x[position], dtype=np.float32)
        pre = np.clip((patch[list(self.pre_indices)] - self.lo) / self.scale, 0, 1)
        post = np.clip((patch[list(self.post_indices)] - self.lo) / self.scale, 0, 1)
        x_t = torch.from_numpy(np.concatenate([pre, post], axis=0).copy())
        half = len(self.pre_indices)

        if self.augment:
            if torch.rand(()) < 0.5:
                x_t = torch.flip(x_t, dims=(2,))
            if torch.rand(()) < 0.5:
                x_t = torch.flip(x_t, dims=(1,))
            rotations = int(torch.randint(0, 4, ()).item())
            if rotations:
                x_t = torch.rot90(x_t, rotations, dims=(1, 2))
            if self.brightness_jitter:
                amount = self.brightness_jitter
                x_t[:half] = torch.clamp(
                    x_t[:half] + torch.empty(()).uniform_(-amount, amount), 0, 1
                )
                x_t[half:] = torch.clamp(
                    x_t[half:] + torch.empty(()).uniform_(-amount, amount), 0, 1
                )

        return x_t, torch.tensor(self.y[position], dtype=torch.float32)


def _planet_conv_block(cin: int, cout: int) -> nn.Sequential:
    """The exact convolutional block used by the S1 BaseCNN."""
    return nn.Sequential(
        nn.Conv2d(cin, cout, kernel_size=3, padding=1),
        nn.BatchNorm2d(cout),
        nn.ReLU(),
        nn.MaxPool2d(2),
    )


class BasePlanetCNN(nn.Module):
    """S1 BaseCNN unchanged except for the number of input channels."""

    def __init__(self, n_channels: int, width: int = 8, depth: int = 2, dropout: float = 0.2):
        super().__init__()
        chans = [n_channels] + [width * (2 ** i) for i in range(depth)]
        self.features = nn.Sequential(
            *[_planet_conv_block(chans[i], chans[i + 1]) for i in range(depth)]
        )
        self.head = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Flatten(),
            nn.Dropout(dropout),
            nn.Linear(chans[-1], 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.head(self.features(x)).squeeze(1)


class SiamesePlanetCNN(nn.Module):
    """S1-style shared encoder with an explicit signed change feature."""

    def __init__(
        self,
        n_channels: int,
        width: int = 32,
        depth: int = 3,
        dropout: float = 0.4,
        head_dim: int = 128,
        head_dropout: float = 0.2,
    ):
        super().__init__()
        if n_channels % 2:
            raise ValueError("siamese_cnn needs matching pre and post channels")
        chans = [n_channels // 2] + [width * (2 ** i) for i in range(depth)]
        self.encoder = nn.Sequential(
            *[_planet_conv_block(chans[i], chans[i + 1]) for i in range(depth)],
            nn.AdaptiveAvgPool2d(1),
            nn.Flatten(),
        )
        self.half_channels = n_channels // 2
        self.head = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(3 * chans[-1], head_dim),
            nn.ReLU(),
            nn.Dropout(head_dropout),
            nn.Linear(head_dim, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        pre_features = self.encoder(x[:, : self.half_channels])
        post_features = self.encoder(x[:, self.half_channels :])
        joined = torch.cat(
            [pre_features, post_features, post_features - pre_features], dim=1
        )
        return self.head(joined).squeeze(1)


PLANET_MODEL_REGISTRY = {
    "base_cnn": BasePlanetCNN,
    "siamese_cnn": SiamesePlanetCNN,
}


def build_planet_model(
    name: str,
    n_channels: int,
    **model_parameters: object,
) -> nn.Module:
    if name not in PLANET_MODEL_REGISTRY:
        raise ValueError(f"Unknown Planet model {name}; choose {sorted(PLANET_MODEL_REGISTRY)}")
    return PLANET_MODEL_REGISTRY[name](n_channels=n_channels, **model_parameters)


@torch.inference_mode()
def predict_planet_probs(
    model: nn.Module,
    loader: torch.utils.data.DataLoader,
    device: torch.device | str,
) -> tuple[np.ndarray, np.ndarray]:
    """Return probabilities and labels in deterministic loader order."""
    model.eval()
    probabilities, labels = [], []
    for x, y in loader:
        logits = model(x.to(device, non_blocking=True))
        probabilities.append(torch.sigmoid(logits).cpu().numpy())
        labels.append(y.numpy())
    return np.concatenate(probabilities), np.concatenate(labels).astype(np.int8)


def neighbour_features(
    xy: np.ndarray,
    scores: np.ndarray,
    ks: Sequence[int] = (8, 32),
) -> pd.DataFrame:
    """Build leakage-safe spatial features within one split region only."""
    from sklearn.neighbors import BallTree

    xy = np.asarray(xy, dtype=np.float64)
    scores = np.asarray(scores, dtype=np.float32)
    if len(xy) != len(scores):
        raise ValueError("xy and scores must have the same number of rows")
    if any(int(k) < 1 for k in ks):
        raise ValueError("All neighbour counts must be positive")

    n = len(scores)
    features: dict[str, np.ndarray] = {"score": scores}
    if n < 2:
        for k in ks:
            for suffix in ("mean", "std", "max", "min", "dev", "dist"):
                features[f"k{k}_{suffix}"] = np.zeros(n, np.float32)
        return pd.DataFrame(features)

    tree = BallTree(xy)
    max_k = min(max(int(k) for k in ks) + 1, n)
    distances, neighbours = tree.query(xy, k=max_k)
    for k in ks:
        k_eff = min(int(k), max_k - 1)
        neighbour_scores = scores[neighbours[:, 1 : k_eff + 1]]
        neighbour_distances = distances[:, 1 : k_eff + 1]
        mean = neighbour_scores.mean(axis=1)
        features[f"k{k}_mean"] = mean
        features[f"k{k}_std"] = neighbour_scores.std(axis=1)
        features[f"k{k}_max"] = neighbour_scores.max(axis=1)
        features[f"k{k}_min"] = neighbour_scores.min(axis=1)
        features[f"k{k}_dev"] = scores - mean
        features[f"k{k}_dist"] = neighbour_distances.mean(axis=1)

    k_near = min(8, max_k - 1)
    nearest = np.sort(scores[neighbours[:, 1 : k_near + 1]], axis=1)[:, ::-1]
    for i in range(k_near):
        features[f"nb{i + 1}"] = nearest[:, i]
    return pd.DataFrame(
        {name: np.asarray(values, np.float32) for name, values in features.items()}
    )


def best_f1_threshold(y_true: np.ndarray, scores: np.ndarray) -> tuple[float, float]:
    precision, recall, thresholds = precision_recall_curve(y_true, scores)
    if not len(thresholds):
        return 0.5, 0.0
    f1 = 2 * precision[:-1] * recall[:-1] / np.maximum(
        precision[:-1] + recall[:-1], 1e-12
    )
    best = int(np.nanargmax(f1))
    return float(thresholds[best]), float(f1[best])


def binary_metrics(y_true: np.ndarray, scores: np.ndarray, threshold: float) -> dict[str, float | int]:
    y_true = np.asarray(y_true, dtype=np.int8)
    scores = np.asarray(scores, dtype=np.float64)
    predicted = (scores >= threshold).astype(np.int8)
    tn = int(((y_true == 0) & (predicted == 0)).sum())
    fp = int(((y_true == 0) & (predicted == 1)).sum())
    fn = int(((y_true == 1) & (predicted == 0)).sum())
    tp = int(((y_true == 1) & (predicted == 1)).sum())
    return {
        "n": int(len(y_true)),
        "prevalence": float(y_true.mean()),
        "threshold": float(threshold),
        "PR_AUC": float(average_precision_score(y_true, scores)),
        "ROC_AUC": float(roc_auc_score(y_true, scores)),
        "precision": float(precision_score(y_true, predicted, zero_division=0)),
        "recall": float(recall_score(y_true, predicted, zero_division=0)),
        "F1": float(f1_score(y_true, predicted, zero_division=0)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, predicted)),
        "specificity": float(tn / max(tn + fp, 1)),
        "TN": tn,
        "FP": fp,
        "FN": fn,
        "TP": tp,
    }


def experiment_dirs(experiment_name: str) -> dict[str, Path]:
    """Create and return the persistent folders for one Planet experiment."""
    if not experiment_name or Path(experiment_name).name != experiment_name:
        raise ValueError("experiment_name must be one non-empty folder name")
    root = EXPERIMENTS_DIR / experiment_name
    dirs = {name: root / name for name in ("models", "metrics", "figures", "predictions")}
    dirs["root"] = root
    for path in dirs.values():
        path.mkdir(parents=True, exist_ok=True)
    return dirs


