def _npy_member_header(npz_path: Path, key: str) -> dict[str, object]:
    """Read an array's shape/dtype from an NPZ without decompressing its data."""
    member_name = f"{key}.npy"
    with zipfile.ZipFile(npz_path) as archive:
        if member_name not in archive.namelist():
            raise KeyError(f"{member_name} not found in {npz_path.name}")
        with archive.open(member_name) as member:
            version = np.lib.format.read_magic(member)
            if version == (1, 0):
                shape_, fortran, dtype_ = np.lib.format.read_array_header_1_0(member)
            elif version == (2, 0):
                shape_, fortran, dtype_ = np.lib.format.read_array_header_2_0(member)
            else:
                raise ValueError(
                    f"Unsupported NPY header version {version} for {member_name}"
                )
    return {"shape": tuple(shape_), "dtype": str(dtype_), "fortran_order": bool(fortran)}


def inspect_dataset(validate_alignment: bool = True) -> dict[str, object]:
    """Inspect the saved pair without inflating the multi-gigabyte X member."""
    npz_path, parquet_path = dataset_paths()
    if not npz_path.exists() or not parquet_path.exists():
        raise FileNotFoundError(f"Dataset pair not found: {npz_path}, {parquet_path}")

    x_header = _npy_member_header(npz_path, "X")
    with np.load(npz_path, allow_pickle=False) as data:
        y = data["y"].astype(np.int8)
        channel_names = tuple(str(v) for v in data["channel_names"].tolist())
        ids = data["system_index"].astype(str)
        metadata = json.loads(str(data["metadata_json"].item()))

    buildings = gpd.read_parquet(parquet_path)
    if validate_alignment:
        if x_header["shape"][0] != len(y) or len(y) != len(buildings):
            raise ValueError(
                f"Row mismatch: X={x_header['shape'][0]}, y={len(y)}, "
                f"parquet={len(buildings)}"
            )
        parquet_ids = buildings["system:index"].astype(str).to_numpy()
        if not np.array_equal(ids, parquet_ids):
            raise ValueError("NPZ system_index and parquet system:index are not row-aligned")
        parquet_fingerprints = set(
            buildings["preprocessing_fingerprint"].dropna().astype(str).unique()
        )
        if parquet_fingerprints != {metadata.get("preprocessing_fingerprint")}:
            raise ValueError(
                "NPZ and parquet preprocessing fingerprints do not describe the same export"
            )
        if set(buildings["dataset_id"].dropna().astype(str).unique()) != {DATASET_ID}:
            raise ValueError("Parquet dataset_id does not match the requested dataset")
        if channel_names != PLANET_CHANNELS:
            raise ValueError(f"Unexpected channels: {channel_names}")
        if tuple(x_header["shape"][1:]) != (
            len(PLANET_CHANNELS),
            PREP["patch_size"],
            PREP["patch_size"],
        ):
            raise ValueError(f"Unexpected X shape: {x_header['shape']}")
        if metadata.get("preprocessing_fingerprint") != preprocessing_fingerprint():
            raise ValueError("Saved preprocessing fingerprint does not match pipeline.py")

    return {
        "npz": str(npz_path),
        "parquet": str(parquet_path),
        "rows": int(len(y)),
        "damaged": int(y.sum()),
        "intact": int((y == 0).sum()),
        "damaged_fraction": float(y.mean()),
        "X_shape": x_header["shape"],
        "X_dtype": x_header["dtype"],
        "channels": channel_names,
        "npz_GB": npz_path.stat().st_size / 1e9,
        "parquet_MB": parquet_path.stat().st_size / 1e6,
        "metadata": metadata,
    }


def load_dataset(load_images: bool = True) -> dict[str, object]:
    """Load the saved pair for modeling.

    ``load_images=True`` inflates the compressed X member into RAM (roughly
    3.3 GB before raster-coverage filtering).  Notebook 1 should normally use
    :func:`inspect_dataset` and :func:`read_saved_patches` instead.
    """
    info = inspect_dataset(validate_alignment=True)
    npz_path, parquet_path = dataset_paths()
    with np.load(npz_path, allow_pickle=False) as data:
        result: dict[str, object] = {
            "y": data["y"].astype(np.int8),
            "lat": data["lat"].astype(np.float64),
            "channel_names": tuple(str(v) for v in data["channel_names"].tolist()),
            "system_index": data["system_index"].astype(str),
            "metadata": json.loads(str(data["metadata_json"].item())),
        }
        if load_images:
            result["X"] = data["X"]
    result["gdf"] = gpd.read_parquet(parquet_path)
    result["info"] = info
    return result


def read_saved_patches(
    rows: Sequence[int] | np.ndarray,
) -> tuple[np.ndarray, gpd.GeoDataFrame]:
    """Re-read selected saved rows from the raster for lightweight notebook EDA.

    This avoids decompressing the full NPZ.  Coordinates recorded in the
    parquet are the exact centres used during extraction.
    """
    _, parquet_path = dataset_paths()
    if not parquet_path.exists():
        raise FileNotFoundError(f"Missing dataset table: {parquet_path}")
    table = gpd.read_parquet(parquet_path)
    positions = np.asarray(rows, dtype=np.int64)
    if positions.ndim != 1 or (len(positions) and (positions.min() < 0 or positions.max() >= len(table))):
        raise IndexError("rows must be one-dimensional valid parquet row positions")

    patch = int(PREP["patch_size"])
    half = patch // 2
    out = np.empty((len(positions), len(PLANET_CHANNELS), patch, patch), np.float32)
    with rasterio.open(planet_raster_path()) as src:
        for k, position in enumerate(positions):
            row = int(table.iloc[position]["raster_row"])
            col = int(table.iloc[position]["raster_col"])
            block = src.read(
                window=Window(col - half, row - half, patch, patch), out_dtype="float32"
            )
            if block.shape != out[k].shape or not np.isfinite(block).all():
                raise RuntimeError(f"Saved row {position} no longer yields a valid Planet patch")
            out[k] = block
    return out, table.iloc[positions].copy()


