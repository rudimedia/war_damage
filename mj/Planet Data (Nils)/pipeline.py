def raster_metadata() -> dict[str, object]:
    path = planet_raster_path()
    if not path.exists():
        raise FileNotFoundError(f"Missing Planet raster: {path}")
    with rasterio.open(path) as src:
        return {
            "path": str(path),
            "bytes": path.stat().st_size,
            "driver": src.driver,
            "width": src.width,
            "height": src.height,
            "count": src.count,
            "crs": str(src.crs),
            "resolution": tuple(float(abs(v)) for v in src.res),
            "bounds": tuple(float(v) for v in src.bounds),
            "dtype": tuple(src.dtypes),
            "nodata": src.nodata,
            "descriptions": tuple(src.descriptions),
            "block_shapes": tuple(src.block_shapes),
        }


def validate_raster() -> dict[str, object]:
    meta = raster_metadata()
    if meta["count"] != len(PLANET_CHANNELS):
        raise ValueError(
            f"Planet raster has {meta['count']} bands; expected {len(PLANET_CHANNELS)}"
        )
    if not np.allclose(meta["resolution"], (PREP["scale_m"], PREP["scale_m"]), atol=1e-6):
        raise ValueError(
            f"Planet raster resolution is {meta['resolution']}; expected 3 m pixels"
        )
    descriptions = tuple(meta["descriptions"])
    if any(descriptions) and descriptions != RASTER_BAND_DESCRIPTIONS:
        raise ValueError(
            "Unexpected Planet band descriptions. "
            f"Found {descriptions}, expected {RASTER_BAND_DESCRIPTIONS}"
        )
    if meta["crs"] in (None, "None"):
        raise ValueError("Planet raster has no CRS")
    return meta


def _centres_and_windows(
    buildings: gpd.GeoDataFrame, src: rasterio.io.DatasetReader
) -> tuple[gpd.GeoDataFrame, np.ndarray, np.ndarray, np.ndarray]:
    patch = int(PREP["patch_size"])
    half = patch // 2

    projected = buildings.to_crs(src.crs).copy()
    centres = projected.geometry.centroid
    xs = centres.x.to_numpy(float)
    ys = centres.y.to_numpy(float)
    cols, rows = (~src.transform) * (xs, ys)
    r0 = np.round(rows).astype(np.int64) - half
    c0 = np.round(cols).astype(np.int64) - half
    fits = (
        (r0 >= 0)
        & (c0 >= 0)
        & (r0 + patch <= src.height)
        & (c0 + patch <= src.width)
    )

    centres_ll = gpd.GeoSeries(centres, crs=src.crs).to_crs("EPSG:4326")
    out = buildings.copy()
    out["lon"] = centres_ll.x.to_numpy(float)
    out["lat"] = centres_ll.y.to_numpy(float)
    out["centroid_x"] = xs
    out["centroid_y"] = ys
    out["raster_row"] = r0 + half
    out["raster_col"] = c0 + half
    return out, r0, c0, fits


def _temporary_paths(npz_path: Path, parquet_path: Path) -> tuple[Path, Path, Path]:
    tmp_x = TEMP_DIR / f".{DATASET_STEM}_X.tmp.npy"
    tmp_npz = DATASET_DIR / f".{npz_path.name}.part"
    tmp_parquet = DATASET_DIR / f".{parquet_path.name}.part"
    return tmp_x, tmp_npz, tmp_parquet


def _cleanup_temporary(paths: Iterable[Path]) -> None:
    for path in paths:
        try:
            path.unlink(missing_ok=True)
        except OSError:
            # Leave a diagnostic artifact rather than hiding the original error.
            pass


def extract_dataset(force: bool = False, progress_every: int = 10_000) -> dict[str, object]:
    """Extract and atomically save the Planet-only dataset.

    Raster tiles are read once with a half-patch halo and all building windows
    centred in that tile are extracted from the in-memory block. Pixels are
    written to a temporary float16 memory map, so the notebook never holds the
    full patch tensor in RAM. A patch is retained only when all eight bands are
    finite and unmasked for the complete 32 x 32 window.
    """
    ensure_directories()
    npz_path, parquet_path = dataset_paths()
    existing = (npz_path.exists(), parquet_path.exists())
    if all(existing) and not force:
        info = inspect_dataset(validate_alignment=True)
        print(f"Dataset already exists and passed validation: {npz_path.name}")
        return info
    if any(existing) and not all(existing) and not force:
        raise RuntimeError(
            "Only one member of the dataset pair exists. Inspect or remove the incomplete "
            f"pair before rerunning with force=True: {npz_path}, {parquet_path}"
        )

    buildings, label_summary = build_filtered_buildings()
    raster_info = validate_raster()
    tmp_x, tmp_npz, tmp_parquet = _temporary_paths(npz_path, parquet_path)
    _cleanup_temporary((tmp_x, tmp_npz, tmp_parquet))

    patch = int(PREP["patch_size"])
    n_channels = len(PLANET_CHANNELS)
    patches = None
    try:
        with rasterio.Env(GDAL_CACHEMAX=512):
            with rasterio.open(planet_raster_path()) as src:
                buildings, r0, c0, fits = _centres_and_windows(buildings, src)
                candidates = np.flatnonzero(fits)
                if not len(candidates):
                    raise RuntimeError("No filtered building has a complete patch inside the raster")

                block_h, block_w = src.block_shapes[0]
                half = patch // 2
                centre_rows = r0[candidates] + half
                centre_cols = c0[candidates] + half
                group_rows = centre_rows // block_h
                group_cols = centre_cols // block_w
                spatial_order = np.lexsort((group_cols, group_rows))
                candidates = candidates[spatial_order]
                group_rows = group_rows[spatial_order]
                group_cols = group_cols[spatial_order]

                patches = open_memmap(
                    tmp_x,
                    mode="w+",
                    dtype=np.float16,
                    shape=(len(candidates), n_channels, patch, patch),
                )
                kept_positions = np.empty(len(candidates), dtype=np.int64)
                n_valid = 0
                rejected_masked = 0
                rejected_nonfinite = 0

                # Read each 512-ish pixel raster tile once with a half-patch
                # halo, then take all building windows centred in that tile.
                # This turns ~200k small Drive reads into only a few hundred.
                boundaries = np.flatnonzero(
                    np.r_[True, (group_rows[1:] != group_rows[:-1]) |
                                   (group_cols[1:] != group_cols[:-1]), True]
                )
                examined = 0
                next_progress = progress_every if progress_every else None
                for start, stop in zip(boundaries[:-1], boundaries[1:]):
                    tile_row = int(group_rows[start])
                    tile_col = int(group_cols[start])
                    win_r0 = max(0, tile_row * block_h - half)
                    win_c0 = max(0, tile_col * block_w - half)
                    win_r1 = min(src.height, (tile_row + 1) * block_h + half)
                    win_c1 = min(src.width, (tile_col + 1) * block_w + half)
                    tile = src.read(
                        window=Window(win_c0, win_r0, win_c1 - win_c0, win_r1 - win_r0),
                        out_dtype="float32",
                        masked=True,
                    )

                    for position in candidates[start:stop]:
                        local_r0 = int(r0[position] - win_r0)
                        local_c0 = int(c0[position] - win_c0)
                        block = tile[
                            :,
                            local_r0:local_r0 + patch,
                            local_c0:local_c0 + patch,
                        ]
                        examined += 1
                        if block.shape != (n_channels, patch, patch):
                            raise RuntimeError(
                                f"Internal tiled-read error at building row {position}: "
                                f"got {block.shape}"
                            )
                        if np.ma.getmaskarray(block).any():
                            rejected_masked += 1
                        else:
                            values = np.asarray(block)
                            if not np.isfinite(values).all():
                                rejected_nonfinite += 1
                            else:
                                patches[n_valid] = values.astype(np.float16)
                                kept_positions[n_valid] = position
                                n_valid += 1

                        if next_progress is not None and examined >= next_progress:
                            print(
                                f"  examined {examined:,}/{len(candidates):,}; "
                                f"kept {n_valid:,}"
                            )
                            next_progress += progress_every

        if not n_valid:
            raise RuntimeError("Every geometrically eligible Planet patch was masked or non-finite")

        patches.flush()
        kept = buildings.iloc[kept_positions[:n_valid]].copy().reset_index(drop=True)
        kept["dataset_id"] = DATASET_ID
        kept["preprocessing_fingerprint"] = preprocessing_fingerprint()
        kept.to_parquet(tmp_parquet, index=False)

        y = kept["class"].to_numpy(np.int8)
        ids = kept["system:index"].astype(str).to_numpy(dtype=str)
        metadata = {
            "dataset_stem": DATASET_STEM,
            "preprocessing_fingerprint": preprocessing_fingerprint(),
            "prep": {
                **PREP,
                "positive_damage_codes": list(PREP["positive_damage_codes"]),
                "channels": list(PREP["channels"]),
            },
            "raster": raster_info,
            "software": {
                "numpy": np.__version__,
                "pandas": pd.__version__,
                "geopandas": gpd.__version__,
                "rasterio": rasterio.__version__,
            },
            "label_summary": label_summary,
            "geometric_candidates": int(len(candidates)),
            "outside_raster_removed": int(len(buildings) - len(candidates)),
            "masked_removed": int(rejected_masked),
            "nonfinite_removed": int(rejected_nonfinite),
            "saved_rows": int(n_valid),
        }
        # Passing an open file handle prevents numpy from appending another
        # .npz suffix to the atomic temporary filename.
        with tmp_npz.open("wb") as handle:
            np.savez_compressed(
                handle,
                X=patches[:n_valid],
                y=y,
                lat=kept["lat"].to_numpy(np.float64),
                channel_names=np.asarray(PLANET_CHANNELS),
                system_index=ids,
                metadata_json=np.asarray(json.dumps(metadata, sort_keys=True)),
            )

        # Existing complete files remain available until both replacements are
        # fully written.  Every file also carries IDs/fingerprint for alignment.
        os.replace(tmp_npz, npz_path)
        os.replace(tmp_parquet, parquet_path)
    finally:
        if patches is not None:
            try:
                patches.flush()
            except Exception:
                pass
            del patches
        _cleanup_temporary((tmp_x, tmp_npz, tmp_parquet))

    info = inspect_dataset(validate_alignment=True)
    print(
        f"Saved {info['rows']:,} Planet patches to {npz_path.name} "
        f"and {parquet_path.name}"
    )
    return info


